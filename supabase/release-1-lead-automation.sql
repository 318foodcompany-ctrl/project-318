create or replace function public.submit_release1_lead(
  p_idempotency_key uuid,
  p_request_hash text,
  p_rate_limit_key text,
  p_rate_limit_max integer,
  p_rate_limit_window_seconds integer,
  p_submission_source text,
  p_name text,
  p_company text,
  p_email text,
  p_phone text,
  p_event_date date,
  p_guests integer,
  p_menu text,
  p_event_type text,
  p_budget numeric,
  p_notes text,
  p_attribution jsonb,
  p_marketing_consent boolean,
  p_disclosure_version text,
  p_disclosure_id text,
  p_disclosure_text text
)
returns table (lead_id bigint, deduplicated boolean)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_existing public.lead_submission_idempotency%rowtype;
  v_lead_id bigint;
  v_customer_id uuid;
  v_count integer;
begin
  if auth.role() <> 'service_role' then
    raise exception 'Server authorization required' using errcode = '42501';
  end if;
  if p_submission_source not in ('guided_quote', 'contact_form') then
    raise exception 'Invalid submission source' using errcode = '22023';
  end if;
  if p_idempotency_key is null
     or length(btrim(coalesce(p_request_hash, ''))) < 32
     or length(btrim(coalesce(p_rate_limit_key, ''))) < 32 then
    raise exception 'Submission security values are invalid' using errcode = '22023';
  end if;

  perform pg_advisory_xact_lock(hashtextextended(p_idempotency_key::text, 0));

  select * into v_existing
  from public.lead_submission_idempotency
  where idempotency_key = p_idempotency_key
  for update;

  if found then
    if v_existing.request_hash <> p_request_hash then
      raise exception 'Idempotency key was already used for another request' using errcode = '23505';
    end if;
    if v_existing.lead_id is null then
      raise exception 'Submission is still processing' using errcode = '40001';
    end if;
    update public.leads set deduplicated = true where id = v_existing.lead_id;
    return query select v_existing.lead_id, true;
    return;
  end if;

  insert into public.lead_submission_idempotency(
    idempotency_key, request_hash, submission_source
  ) values (p_idempotency_key, p_request_hash, p_submission_source);

  perform pg_advisory_xact_lock(hashtextextended(p_rate_limit_key, 1));

  select count(*) into v_count
  from public.lead_rate_limit_events
  where rate_limit_key = p_rate_limit_key
    and created_at >= now() - make_interval(secs => greatest(p_rate_limit_window_seconds, 60));

  if v_count >= least(greatest(p_rate_limit_max, 1), 100) then
    raise exception 'Submission rate limit exceeded' using errcode = 'P0001';
  end if;

  insert into public.lead_rate_limit_events(rate_limit_key) values (p_rate_limit_key);

  v_lead_id := public.submit_quote_with_attribution(
    p_name, p_company, p_email, p_phone, p_event_date, p_guests,
    p_menu, p_event_type, p_budget, p_notes, coalesce(p_attribution, '{}'::jsonb)
  );

  update public.leads
  set submission_source = p_submission_source,
      marketing_consent_status = case when p_marketing_consent then 'granted' else 'declined' end
  where id = v_lead_id
  returning customer_id into v_customer_id;

  insert into public.marketing_consent_history(
    customer_id, lead_id, channel, granted, disclosure_version,
    disclosure_id, disclosure_text, submission_source
  ) values (
    v_customer_id, v_lead_id, 'email', p_marketing_consent,
    p_disclosure_version, p_disclosure_id, p_disclosure_text, p_submission_source
  );

  update public.lead_submission_idempotency
  set lead_id = v_lead_id, completed_at = now()
  where idempotency_key = p_idempotency_key;

  return query select v_lead_id, false;
end;
$$;

