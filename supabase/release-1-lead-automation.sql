create or replace function public.record_lead_email_delivery(
  p_lead_id bigint,
  p_message_type text,
  p_status text,
  p_provider text,
  p_provider_reference text,
  p_failure_code text
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if auth.role() <> 'service_role' then
    raise exception 'Server authorization required' using errcode = '42501';
  end if;
  if p_message_type not in ('owner_notification', 'customer_confirmation')
     or p_status not in ('accepted', 'failed', 'manual_setup') then
    raise exception 'Invalid email delivery state' using errcode = '22023';
  end if;

  insert into public.lead_email_deliveries(
    lead_id, message_type, status, provider, provider_reference,
    failure_code, accepted_at, retry_state
  ) values (
    p_lead_id, p_message_type, p_status,
    left(btrim(coalesce(p_provider, '')), 100),
    left(btrim(coalesce(p_provider_reference, '')), 500),
    left(btrim(coalesce(p_failure_code, '')), 200),
    case when p_status = 'accepted' then now() else null end,
    case when p_status = 'failed' then 'retry_available' else 'not_scheduled' end
  );

  update public.leads
  set customer_confirmation_status = case
        when p_message_type = 'customer_confirmation' then p_status
        else customer_confirmation_status end,
      owner_notification_status = case
        when p_message_type = 'owner_notification' then p_status
        else owner_notification_status end,
      last_email_attempt_at = now()
  where id = p_lead_id;
end;
$$;

revoke all on function public.record_lead_email_delivery(bigint,text,text,text,text,text)
